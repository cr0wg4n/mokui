// Agent accuracy eval: can a model write valid, complete Mokui DSL from written requirements,
// given only the generated cheat sheet?
//
//   ANTHROPIC_API_KEY=... nub eval/run.ts            (EVAL_MODEL overrides the model)
//
// Sends ONLY the synthetic prompts in eval/prompts.json plus the cheat sheet. Costs API tokens.
import { readFileSync, writeFileSync } from 'node:fs'
import { cheatsheet } from '../src/core'
import { extractDsl, score, type Expect } from './score'

const key = process.env.ANTHROPIC_API_KEY
if (!key) {
  console.error('Set ANTHROPIC_API_KEY to run the eval. (Scoring itself is unit-tested offline.)')
  process.exit(1)
}
const model = process.env.EVAL_MODEL ?? 'claude-haiku-5-5'
const prompts: { id: string; prompt: string; expect: Expect }[] = JSON.parse(readFileSync(new URL('./prompts.json', import.meta.url), 'utf8'))
// Every pack by default, so the eval measures writing the DSL, not remembering to load a pack.
// EVAL_PACKS=default evaluates the cheaper core+overlay sheet instead.
const packs = process.env.EVAL_PACKS === 'default' ? undefined : 'all'
const system = `You draft UI mocks in the Mokui DSL. Reply with only the DSL in one code block.\n\n${cheatsheet({ packs })}`

async function ask(messages: { role: 'user' | 'assistant'; content: string }[]): Promise<string> {
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: { 'x-api-key': key!, 'anthropic-version': '2023-06-01', 'content-type': 'application/json' },
    body: JSON.stringify({ model, max_tokens: 2000, system, messages }),
  })
  if (!res.ok) throw new Error(`API ${res.status}: ${await res.text()}`)
  const data = (await res.json()) as { content: { type: string; text?: string }[] }
  return data.content.map((c) => c.text ?? '').join('')
}

const rows: string[] = ['| Prompt | 1st try valid | 1st try complete | After 1 repair valid | After 1 repair complete |', '|---|:-:|:-:|:-:|:-:|']
let v1 = 0, c1 = 0, v2 = 0, c2 = 0
for (const p of prompts) {
  const first = await ask([{ role: 'user', content: p.prompt }])
  const s1 = score(extractDsl(first), p.expect)
  let s2 = s1
  if (!s1.ok) {
    const feedback = s1.parses ? `Missing: ${s1.missing.join('; ')}. Fix it.` : `Errors:\n${s1.errors.join('\n')}\nFix it.`
    const second = await ask([{ role: 'user', content: p.prompt }, { role: 'assistant', content: first }, { role: 'user', content: feedback }])
    s2 = score(extractDsl(second), p.expect)
  }
  v1 += +s1.parses; c1 += +s1.ok; v2 += +s2.parses; c2 += +s2.ok
  const mark = (b: boolean) => (b ? 'yes' : 'no')
  rows.push(`| ${p.id} | ${mark(s1.parses)} | ${mark(s1.ok)} | ${mark(s2.parses)} | ${mark(s2.ok)} |`)
  console.log(p.id, s1.ok ? 'ok' : s1.parses ? `missing ${s1.missing.join('; ')}` : `invalid ${s1.errors[0]}`)
}
const n = prompts.length
rows.push(`| **total** | ${v1}/${n} | ${c1}/${n} | ${v2}/${n} | ${c2}/${n} |`)
const out = `# Agent accuracy results\n\nModel: ${model}. Generated by \`nub eval/run.ts\`.\n\n${rows.join('\n')}\n`
writeFileSync(new URL('./RESULTS.md', import.meta.url), out)
console.log('\n' + rows.join('\n'))
