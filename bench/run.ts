// Token benchmark: DSL vs HTML equivalents.
// Usage: nub bench/run.ts   (writes bench/RESULTS.md)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { encode } from 'gpt-tokenizer' // o200k_base, a proxy for LLM token cost
import { cheatsheet, html as compileHtml } from '../src/core'

const dir = new URL('./fixtures/', import.meta.url)
const names = readdirSync(dir).filter((f) => f.endsWith('.mk')).map((f) => f.slice(0, -3)).sort()
const tok = (s: string) => encode(s).length

// "Pretty" HTML: what an LLM typically writes (indented, one tag per line).
function pretty(html: string): string {
  const out: string[] = []
  let depth = 0
  for (const part of html.replace(/></g, '>\n<').split('\n')) {
    if (part.startsWith('</')) depth--
    out.push('  '.repeat(Math.max(depth, 0)) + part)
    if (/^<[^/][^>]*[^/]>$/.test(part) && !part.includes('</')) depth++
  }
  return out.join('\n')
}

type Row = { name: string; dsl: number; html: number; pretty: number; tw: number; chars: number }
const rows: Row[] = names.map((name) => {
  const mk = readFileSync(new URL(`${name}.mk`, dir), 'utf8').trim()
  const tw = readFileSync(new URL(`${name}.tw.html`, dir), 'utf8').trim()
  const html = compileHtml(mk) // validates against the registry and expands recipes
  return { name, dsl: tok(mk), html: tok(html), pretty: tok(pretty(html)), tw: tok(tw), chars: mk.length }
})

const sum = (k: keyof Row) => rows.reduce((a, r) => a + (r[k] as number), 0)
const pct = (a: number, b: number) => `${Math.round((1 - a / b) * 100)}%`

const lines = [
  '| Fixture | DSL | mk HTML (compact) | mk HTML (pretty) | Tailwind HTML | DSL vs compact | DSL vs pretty | DSL vs Tailwind |',
  '|---|---:|---:|---:|---:|---:|---:|---:|',
  ...rows.map(
    (r) => `| ${r.name} | ${r.dsl} | ${r.html} | ${r.pretty} | ${r.tw} | -${pct(r.dsl, r.html)} | -${pct(r.dsl, r.pretty)} | -${pct(r.dsl, r.tw)} |`,
  ),
  `| **total** | **${sum('dsl')}** | **${sum('html')}** | **${sum('pretty')}** | **${sum('tw')}** | **-${pct(sum('dsl'), sum('html'))}** | **-${pct(sum('dsl'), sum('pretty'))}** | **-${pct(sum('dsl'), sum('tw'))}** |`,
]
// Cheat sheet: one-time cost the DSL needs and HTML/Tailwind do not (models already know them).
const sheet = tok(cheatsheet())
const avgSaveTw = (sum('tw') - sum('dsl')) / rows.length
const avgSaveHtml = (sum('pretty') - sum('dsl')) / rows.length
const extra = [
  '',
  `Cheat sheet: ${sheet} tokens (generated by \`mokui cheatsheet\`).`,
  `Average saving per mock: ${Math.round(avgSaveTw)} tokens vs Tailwind, ${Math.round(avgSaveHtml)} vs pretty mk HTML.`,
  `Break-even: the cheat sheet pays for itself after about ${Math.ceil(sheet / avgSaveTw)} mocks vs Tailwind (${Math.ceil(sheet / avgSaveHtml)} vs pretty mk HTML) in the same context.`,
]
lines.push(...extra)
console.log(lines.join('\n'))
writeFileSync(new URL('./RESULTS.md', import.meta.url), `# Token benchmark results\n\nGenerated by \`nub bench/run.ts\`. Tokenizer: gpt-tokenizer (o200k_base), a proxy, not Claude's tokenizer.\n\n${lines.join('\n')}\n`)
